#!/usr/bin/env python
"""Robustness (E2, Y full) -> results/analysis/robustness.{md,tsv}.
Input: results/robustness/<pert>_<tool>.tsv (evaluation agent; per unit: clean vs perturbed value, delta) and
results/robustness/noise_floor_orthofinder.tsv (OF default re-run vs default).
Unit of analysis = reference family / YGOB unit (headline, non-control); mean delta with a unit bootstrap 95% CI
(2,000 resamples, seed SEEDS[3]); affected vs unaffected genes via gene_frac_correct_{affected,unaffected}.
Fragmentation is reported under both pre-registered credit rules (either / both fragments)."""
import glob
import numpy as np
import pandas as pd
from common import ROOT, OUT, SEEDS, fmt, write_md

MET = ["level_bcubed_f1", "merge_accuracy_node", "event_recovery_0.5", "membership_f1",
       "gene_frac_correct_affected", "gene_frac_correct_unaffected"]
PERT = {"frag": "fragmentation (10% of members split)", "contam": "contamination (20 distant proteins)",
        "alttree": "alternative species tree (one contested node)", "taxrm": "taxon removal (one clade)"}


def ci(x, seed):
    x = np.asarray(x, float); x = x[np.isfinite(x)]
    if len(x) < 5:
        return np.nan, np.nan
    rng = np.random.default_rng(seed)
    b = x[rng.integers(0, len(x), (2000, len(x)))].mean(1)
    return np.percentile(b, [2.5, 97.5])


def main():
    d = pd.concat([pd.read_csv(f, sep="\t", keep_default_na=False, na_values=["", "NA", "None", "nan"],
                               dtype={"variant": str, "credit": str})
                   for f in sorted(glob.glob(str(ROOT / "results/robustness/*_*_*.tsv"))) if "noise_floor" not in f])
    d = d[(d.track != "control") & (d.headline == 1)].dropna(subset=["delta"])
    d["credit"] = d.credit.fillna("")
    rows = []
    for (p, t, v, c, m), g in d.groupby(["pert", "tool", "variant", "credit", "metric"]):
        lo, hi = ci(g.delta, SEEDS[3])
        rows.append({"pert": p, "tool": t, "variant": v, "credit": c, "metric": m, "n_units": len(g),
                     "clean": g.clean.mean(), "perturbed": g.perturbed.mean(), "delta": g.delta.mean(), "ci_lo": lo, "ci_hi": hi,
                     "n_units_changed": int((g.delta.abs() > 1e-9).sum())})
    R = pd.DataFrame(rows); R.to_csv(OUT / "robustness.tsv", sep="\t", index=False, float_format="%.5f")
    nf = pd.read_csv(ROOT / "results/robustness/noise_floor_orthofinder.tsv", sep="\t", na_values=["", "NA", "None"])
    nfmax = nf.delta.abs().max(); nfn = nf.delta.notna().sum()
    L = ["# Robustness (Y full; seed 1)", "", "Generated by scripts/analysis/robustness.py from results/robustness/*.tsv. "
         "Mean delta = perturbed - clean over headline YGOB units + Y03 (unit = cluster; bootstrap 95% CI). "
         f"Noise floor: OrthoFinder default re-run vs default, max |delta| = {nfmax:g} over {nfn} unit x metric values "
         "(bit-identical), so any non-zero delta below is attributable to the perturbation (single seed per perturbation).", ""]
    tools = ["orthofinder", "fastoma", "of_flat"]
    for p in ["frag", "contam", "alttree", "taxrm"]:
        s = R[R.pert == p]
        if s.empty:
            continue
        L += [f"## {PERT[p]}", "", "| credit | metric | " + " | ".join(f"{t}: delta [95% CI] (n; n changed)" for t in tools) + " |",
              "|---|---|" + "---|" * len(tools)]
        for (c, m), g in s.groupby(["credit", "metric"], sort=False):
            if m not in MET:
                continue
            cells = []
            for t in tools:
                r = g[g.tool == t]
                cells.append("" if r.empty else f"{r.delta.iloc[0]:+.4f} [{r.ci_lo.iloc[0]:+.4f}, {r.ci_hi.iloc[0]:+.4f}] "
                             f"({r.n_units.iloc[0]}; {r.n_units_changed.iloc[0]})")
            L.append(f"| {c or '-'} | {m} | " + " | ".join(cells) + " |")
        L.append("")
    g = lambda p, t, c, m: R[(R.pert == p) & (R.tool == t) & (R.credit == c) & (R.metric == m)].iloc[0]
    def dl(p, t, c, m):
        r = g(p, t, c, m); return f"{r.delta:+.3f} [{r.ci_lo:+.3f}, {r.ci_hi:+.3f}]"
    L += ["## Interpretation", "",
          "- Fragmentation is the only perturbation with a material effect. Under the strict rule (both fragments must be placed "
          f"correctly), merge accuracy changes by OF {dl('frag', 'orthofinder', 'both', 'merge_accuracy_node')}, FastOMA "
          f"{dl('frag', 'fastoma', 'both', 'merge_accuracy_node')}, of_flat {dl('frag', 'of_flat', 'both', 'merge_accuracy_node')}; "
          f"affected-gene correctness OF {dl('frag', 'orthofinder', 'both', 'gene_frac_correct_affected')} vs FastOMA "
          f"{dl('frag', 'fastoma', 'both', 'gene_frac_correct_affected')}. Under the pre-registered primary rule (parent credited if either "
          f"fragment is correct) OF is essentially unaffected (merge {dl('frag', 'orthofinder', 'either', 'merge_accuracy_node')}) while "
          f"FastOMA still loses {dl('frag', 'fastoma', 'either', 'merge_accuracy_node')}, and its unaffected genes also degrade "
          f"({dl('frag', 'fastoma', 'either', 'gene_frac_correct_unaffected')}): fragments perturb FastOMA's grouping of intact genes.",
          "- Contamination, alternative species tree and taxon removal: all |mean delta| <= 0.005 on the primary endpoints; some CIs exclude 0 "
          "(the noise floor is exactly 0, so these are real but negligible effects; e.g. alt-tree B-cubed "
          f"OF {dl('alttree', 'orthofinder', '', 'level_bcubed_f1')}, FastOMA {dl('alttree', 'fastoma', '', 'level_bcubed_f1')}).",
          "- Limits: one seed per perturbation; contamination = 20 proteins of one distant species in one proteome (few reference genes "
          "affected: n=8-13 units); one contested node for the alternative tree; one removed clade; event recovery has n=202 testable "
          "events and wide CIs; membership is not defined on Y. Y full only; results do not transfer automatically to other panels.", ""]
    write_md(OUT / "robustness.md", L)


if __name__ == "__main__":
    main()
