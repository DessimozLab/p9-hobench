#!/usr/bin/env python
"""Phenomenon analysis -> results/analysis/phenomena.md (+ phenomena_*.tsv).
1. Family-level tags (results/catalogue/families.tsv `phenomena`; a collection item carries its collection's tags):
   headline item counts and primary-endpoint means per method.
2. Event-level tags (events.tsv `tags`): testable internal-branch events, recovery_0.5 per method (event-pooled; n events, n items).
3. Within-family contrast (pairs, from results/analysis/cache/nodes_*.tsv.gz): node-balanced merge accuracy of reference
   D nodes tagged WGD or ALLO minus that of S nodes, per family/unit having both; mean over clusters with a cluster
   bootstrap 95% CI (2,000 resamples, seed SEEDS[1]; no CI when n<5).
4. YGOB hidden-paralogy trap: pseudo-ortholog pairs (LCA = WGD D node tagged LOSS: the two genes sit on different
   tracks, each sister copy lost) vs same-track ortholog pairs (LCA = S node below PostWGD). Fraction of pairs whose
   predicted merge level is in the reference interval, pair-pooled over units, unit-cluster bootstrap CI."""
import numpy as np
import pandas as pd
from common import ROOT, OUT, PRIMARY, SEEDS, available, items, read_tsv, fmt, mlabel, write_md
from hobench.speciestree import SpeciesTree

METH = [("orthofinder", "default"), ("orthofinder", "dendroblast"), ("fastoma", "default_declared"),
        ("of_flat", "default"), ("one_big_hog", ""), ("all_singletons", "")]
TOOLS = [("orthofinder", "default"), ("orthofinder", "dendroblast"), ("fastoma", "default_declared")]
NB = 2000


def coll_names():
    import yaml
    m = {}
    for p in (ROOT / "families").glob("*/collection.yaml"):
        m[yaml.safe_load(p.read_text())["collection"]] = p.parent.name
    return m


def boot(clusters, stat, seed):
    rng = np.random.default_rng(seed)
    n = len(clusters)
    if n < 5:
        return None, None
    v = [stat(clusters[rng.integers(0, n, n)]) for _ in range(NB)]
    return tuple(np.nanpercentile(v, [2.5, 97.5]))


def main():
    av = available()
    cat = pd.read_csv(ROOT / "results/catalogue/families.tsv", sep="\t", keep_default_na=False)
    ph = dict(zip(cat.id, cat.phenomena)); cn = coll_names()
    L = ["# Phenomena", "", "Panels: " + ", ".join(f"{P} {m}" for P, m in av) + ". Headline track only; descriptive; "
         "a collection is one item. Generated by scripts/analysis/phenomena.py.", ""]
    # ---- 1 family tags
    it = pd.concat([items(P, m) for P, m in av])
    it["tags"] = [ph.get(cn.get(i.split(":", 1)[1], ""), "") if i.startswith("collection:") else ph.get(i, "")
                  for i in it["item"]]
    tagset = sorted({t for s in it.tags for t in s.split(",") if t})
    rows = []
    for t in tagset:
        s = it[it.tags.str.split(",").apply(lambda x: t in x)]
        for m, v in METH:
            r = {"tag": t, "n_items": s["item"].nunique(), "panels": "".join(sorted(s.panel.unique())), "method": mlabel(m, v)}
            for e in PRIMARY:
                x = s[(s.method == m) & (s.variant == v) & (s.metric == e)]["value"]
                r[e] = x.mean() if len(x) else np.nan; r["n_" + e] = len(x)
            rows.append(r)
    T1 = pd.DataFrame(rows); T1.to_csv(OUT / "phenomena_family_tags.tsv", sep="\t", index=False, float_format="%.4f")
    L += ["## 1. Family-level phenomenon tags (items; mean of primary endpoint, n items in brackets)", "",
          "| tag | panels | n items | method | " + " | ".join(PRIMARY) + " |", "|" + "---|" * (4 + len(PRIMARY))]
    for _, r in T1.iterrows():
        if r.method in ("one_big_hog", "all_singletons", "orthofinder/dendroblast"):
            continue
        L.append(f"| {r.tag} | {r.panels} | {r.n_items} | {r.method} | " +
                 " | ".join(f"{fmt(r[e])} ({r['n_'+e]})" for e in PRIMARY) + " |")
    L += ["", "Baseline rows (one big HOG, all singletons) and OF dendroblast: phenomena_family_tags.tsv.", ""]
    # ---- 2 event tags
    rows = []
    for P, mode in av:
        ev = read_tsv(P, mode, "events")
        ev["variant"] = ev["variant"].fillna(""); ev["tags"] = ev["tags"].fillna("")
        ev = ev[(ev.testable == 1) & (ev.event_branch == "internal")]
        ev["item"] = np.where(ev.collection.fillna("") != "", "collection:" + ev.collection.fillna(""), ev.family)
        for (m, v) in METH:
            s = ev[(ev.method == m) & (ev.variant == v)]
            for t, g in s.groupby(s.tags.replace("", "(untagged)")):
                rows.append({"panel": P, "mode": mode, "event_tags": t, "method": mlabel(m, v), "n_events": len(g),
                             "n_items": g["item"].nunique(), "n_units": g.family.nunique(),
                             "recovery_0.5": g["recovered_0.5"].mean(), "recovery_0.8": g["recovered_0.8"].mean(),
                             "separation": g["separation"].mean(), "cohesion_min": g["cohesion_min"].mean()})
    T2 = pd.DataFrame(rows); T2.to_csv(OUT / "phenomena_event_tags.tsv", sep="\t", index=False, float_format="%.4f")
    L += ["## 2. Event-level tags (testable internal-branch events; event-pooled)", "",
          "| panel | event tags | method | n events (units) | recovery 0.5 | recovery 0.8 | separation (apart) | min cohesion |",
          "|---|---|---|---|---|---|---|---|"]
    for _, r in T2[T2.method.isin(["orthofinder", "orthofinder/default", "fastoma/default_declared"])].iterrows():
        L.append(f"| {r.panel} | {r.event_tags} | {r.method} | {r.n_events} ({r.n_units}) | {fmt(r['recovery_0.5'])} | "
                 f"{fmt(r['recovery_0.8'])} | {fmt(r.separation)} | {fmt(r.cohesion_min)} |")
    L += ["", "separation = fraction of cross-copy pairs apart at the event level; cohesion_min = min over copies of the "
          "fraction of reference-together pairs kept together (events.tsv definitions).", ""]
    # ---- 3 + 4 pair-level contrasts
    L += ["## 3. Within-family contrast: D nodes tagged WGD/ALLO vs S nodes (node-balanced merge accuracy)", "",
          "Per cluster (family, or unit of a collection) having both node types: mean acc(D[WGD|ALLO]) - mean acc(S). "
          "CI = cluster bootstrap 95%.", "",
          "| panel | method | n clusters | acc D[WGD/ALLO] | acc S | mean diff D-S | 95% CI |", "|---|---|---|---|---|---|---|"]
    trap_rows, c_rows = [], []
    for P, mode in av:
        f = OUT / "cache" / f"nodes_{P}_{mode}.tsv.gz"
        if not f.exists():
            L.append(f"| {P} | (node extraction missing) | | | | | |"); continue
        nd = pd.read_csv(f, sep="\t", keep_default_na=False, dtype={"variant": str})
        nd["acc"] = nd.n_correct / nd.n_pairs
        nd["wgd"] = (nd.ev == "D") & nd.tags.str.contains("WGD|ALLO")
        for m, v in TOOLS:
            s = nd[(nd.method == m) & (nd.variant == v)]
            if s.empty:
                continue
            a = s[s.wgd].groupby("family").acc.mean(); b = s[s.ev == "S"].groupby("family").acc.mean()
            j = pd.concat([a.rename("d"), b.rename("s")], axis=1, join="inner")
            if j.empty:
                L.append(f"| {P} | {mlabel(m, v)} | 0 | | | | |"); continue
            diff = (j.d - j.s).to_numpy()
            ci = boot(diff, np.mean, SEEDS[1])
            c_rows.append({"panel": P, "method": mlabel(m, v), "n_clusters": len(j), "acc_D": j.d.mean(), "acc_S": j.s.mean(),
                           "diff": diff.mean(), "ci_lo": ci[0], "ci_hi": ci[1]})
            L.append(f"| {P} | {mlabel(m, v)} | {len(j)} | {fmt(j.d.mean())} | {fmt(j.s.mean())} | {fmt(diff.mean())} | "
                     + (f"[{fmt(ci[0])}, {fmt(ci[1])}]" if ci[0] is not None else "n<5") + " |")
        if P == "Y":
            st = SpeciesTree.from_newick(str(ROOT / "panels/Y/species_tree.nwk"))
            wgd = st.names.index("PostWGD") if isinstance(st.names, list) else list(st.names).index("PostWGD")
            idx = {n_: k for k, n_ in enumerate(st.names)}
            y = nd[nd.collection == "YGOB"].copy()
            y["below_wgd"] = [bool(st.anc[wgd, idx[l]]) and l != "PostWGD" for l in y.node_level]
            y["cls"] = np.where((y.ev == "D") & y.tags.str.contains("LOSS"), "pseudo",
                                np.where((y.ev == "S") & y.below_wgd, "same_track", ""))
            y = y[y.cls != ""]
            for m, v in TOOLS:
                s = y[(y.method == m) & (y.variant == v)]
                if s.empty:
                    continue
                agg = s.groupby(["family", "cls"])[["n_pairs", "n_correct", "n_over_split", "n_over_merged"]].sum().unstack(fill_value=0)
                units = agg.to_numpy(); cols = list(agg.columns)
                ci_ = {c: cols.index(("n_correct", c)) for c in ("pseudo", "same_track")}
                cp = {c: cols.index(("n_pairs", c)) for c in ("pseudo", "same_track")}
                frac = lambda U, c: U[:, ci_[c]].sum() / U[:, cp[c]].sum()
                r = {"method": mlabel(m, v)}
                for c in ("pseudo", "same_track"):
                    r[f"n_pairs_{c}"] = int(units[:, cp[c]].sum()); r[f"n_units_{c}"] = int((units[:, cp[c]] > 0).sum())
                    r[f"frac_correct_{c}"] = frac(units, c)
                    r[f"ci_{c}"] = boot(units, lambda U, c=c: frac(U, c), SEEDS[2])
                    r[f"frac_over_merged_{c}"] = units[:, cols.index(("n_over_merged", c))].sum() / units[:, cp[c]].sum()
                    r[f"frac_over_split_{c}"] = units[:, cols.index(("n_over_split", c))].sum() / units[:, cp[c]].sum()
                r["diff"] = r["frac_correct_same_track"] - r["frac_correct_pseudo"]
                r["ci_diff"] = boot(units, lambda U: frac(U, "same_track") - frac(U, "pseudo"), SEEDS[2])
                trap_rows.append(r)
    pd.DataFrame(c_rows).to_csv(OUT / "phenomena_wgd_vs_s.tsv", sep="\t", index=False, float_format="%.4f")
    L += ["", "## 4. YGOB hidden-paralogy trap (Y full)", "",
          "pseudo-orthologs: pair under a WGD D node tagged LOSS (reciprocal loss: genes on different tracks; correct = not "
          "merged below PostWGD). same-track orthologs: pair whose LCA is an S node below PostWGD (correct = merged at "
          "that S level). Pair-pooled over YGOB units; CI = unit-cluster bootstrap 95% (seed SEEDS[2]).", "",
          "| method | pseudo-ortholog pairs (units) | frac correct [CI] | frac over-merged | same-track pairs (units) | "
          "frac correct [CI] | frac over-split | diff same-track - pseudo [CI] |", "|---|---|---|---|---|---|---|---|"]
    cis = lambda c: f"[{fmt(c[0])}, {fmt(c[1])}]" if c and c[0] is not None else ""
    for r in trap_rows:
        L.append(f"| {r['method']} | {r['n_pairs_pseudo']} ({r['n_units_pseudo']}) | {fmt(r['frac_correct_pseudo'])} "
                 f"{cis(r['ci_pseudo'])} | {fmt(r['frac_over_merged_pseudo'])} | {r['n_pairs_same_track']} "
                 f"({r['n_units_same_track']}) | {fmt(r['frac_correct_same_track'])} {cis(r['ci_same_track'])} | "
                 f"{fmt(r['frac_over_split_same_track'])} | {fmt(r['diff'])} {cis(r['ci_diff'])} |")
    if not trap_rows:
        L.append("| (Y node extraction missing) |  |  |  |  |  |  |  |")
    pd.DataFrame([{k: (str(v) if isinstance(v, tuple) else v) for k, v in r.items()} for r in trap_rows]).to_csv(
        OUT / "phenomena_ygob_trap.tsv", sep="\t", index=False, float_format="%.4f")
    write_md(OUT / "phenomena.md", L)


if __name__ == "__main__":
    main()
